// Catálogo sem produtos: em vez da página vazia, aviso "Estamos preparando" com Vitrix e Araújo Tech; com produtos, o aviso some.
const L = require('./lib'); const P = 'araujotech-catalogos';
const { info, sec, check } = L;
(async () => {
  const ADM = ['admin@araujotechsistemas.com', 'AdminTeste#2026'];
  await L.signUp(...ADM);
  const A = await L.open({ w: 1366 }); const a = A.p;
  await a.goto('https://araujotechsistemas.com/admin/'); await a.w(2500);
  await a.fill('#lg_user', ADM[0]); await a.fill('#lg_pass', ADM[1]); await a.press('#lg_pass', 'Enter'); await a.w(5000);
  await a.act('newshop'); await a.w(300);
  await a.set('#ns_name', 'Prepara E2E'); await a.set('#ns_wa', '595981000977');
  await a.act('createshop'); await a.w(4000);
  const shop = await a.evaluate(() => { const s = PL.shops.find(x => x.name === 'Prepara E2E'); return s && { id: s.id }; });
  const URL = 'https://araujotechsistemas.com/loja/' + shop.id + '/';
  const T0 = await L.open({ w: 390 }); await T0.p.goto(URL); await T0.p.w(3000);
  const base = await T0.p.evaluate(() => JSON.parse(JSON.stringify(pub))); await T0.ctx.close();
  base.store.days = Array(7).fill(0).map(() => ({ on: true, a: ['00:00', '23:59'], b: ['', ''] }));
  const pubSave = async cfg => info('publicado: HTTP ' + (await L.fsReq(P, 'PATCH', 'shops/' + shop.id + '?updateMask.fieldPaths=cfg&updateMask.fieldPaths=status', 'owner', L.fields({ cfg: JSON.stringify(cfg), status: 'ativo' }))).status);
  await pubSave(base);
  const C = await L.open({ w: 390, dpr: 2 }); const c = C.p;
  await c.goto(URL); await c.w(5000);
  sec('A. Com produtos: catálogo normal');
  const n0 = await c.evaluate(() => ({ n: (pub.products || []).length, prep: !!document.querySelector('.cprep'), cards: document.querySelectorAll('.pcard').length, wa: (pub.store || {}).whatsapp }));
  info(JSON.stringify(n0));
  check(n0.n > 0 && !n0.prep && n0.cards > 0, 'com produtos, aparecem os produtos e não o aviso');
  sec('B. Sem produtos: aviso de "Estamos preparando"');
  await pubSave(Object.assign({}, base, { products: [] }));
  await c.goto(URL); await c.w(5000);
  const R = await c.evaluate(() => { const b = document.querySelector('.cprep'); return b && { txt: b.textContent.replace(/\s+/g, ' ').trim(), imgs: [...b.querySelectorAll('img')].map(i => i.getAttribute('src')), wa: (b.querySelector('.cp-wa') || {}).href || '', empty: !!document.querySelector('#secs .empty'), q: !!document.querySelector('#q'), top: Math.round(b.getBoundingClientRect().top) }; });
  info(JSON.stringify(R));
  check(R && /Estamos preparando nuestro catálogo/.test(R.txt) && /Muy pronto/.test(R.txt) && !R.empty, 'sem produtos aparece "Estamos preparando nuestro catálogo" (e não "Todavía no hay productos")');
  check(R && !R.q && R.top < 800, 'sem produtos, a busca e as promoções somem e o aviso aparece logo depois do topo');
  check(R && R.imgs.some(s => /vitrix-blanco-nombre\.png$/.test(s)) && R.imgs.some(s => /logo-completo-blanco\.png$/.test(s)), 'mostra o logo do Vitrix e o da Araújo Tech');
  check(R && R.wa === 'https://wa.me/' + n0.wa, 'botão do WhatsApp da loja');
  const q = await c.evaluate(() => { ui.q = 'zzz'; const h = sectionsHTML(pub, true); ui.q = ''; return /cprep/.test(h); });
  check(!q, 'uma busca sem resultado continua mostrando "No encontramos"');
  await c.w(800);
  if (process.env.SHOT_DIR) await c.screenshot({ path: process.env.SHOT_DIR + '/preparando.png', fullPage: true });
  L.done();
})().catch(e => { L.bad('exceção: ' + (e && e.stack || e)); L.done(); });
